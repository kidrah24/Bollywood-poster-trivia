function shuffleArray<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function buildTriviaDeck(roundCount: number): TriviaQuestion[] {
  const selectedPosters = shuffleArray(MOVIE_POSTERS).slice(
    0,
    Math.min(roundCount, MOVIE_POSTERS.length)
  );

  return selectedPosters.map((poster) => {
    const crop = poster.crops[Math.floor(Math.random() * poster.crops.length)];
    const pickedDistractors = shuffleArray(poster.distractors).slice(0, 3);
    const options = shuffleArray([poster.title, ...pickedDistractors]);
    return {
      poster,
      crop,
      options,
    };
  });
}
